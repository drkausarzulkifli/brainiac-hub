const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context=vm.createContext({document:{addEventListener(){}},data:{sessions:[]}});
vm.runInContext(fs.readFileSync('dist/planner.js','utf8'),context);
const validate=context.validateDatedPlacement;
const slot=(mode,date,time,staff=mode==='eip'?'Cikgu Hana':undefined)=>({mode,date,time,staff,key:context.slotKey(mode,date,time,staff)});
const speech=slot('speech','2026-11-14','14:00');
assert.match(validate([],speech,[]),/Pilih/);
assert.match(validate([],speech,['Adam','Sofia']),/seorang/);
assert.equal(validate([],speech,['Adam']),'');
const existing=[{...speech,students:['Adam']}];
assert.match(validate(existing,slot('ot','2026-11-14','14:00'),['Adam']),/sudah dijadualkan/);
assert.equal(validate(existing,slot('ot','2026-11-14','12:45'),['Adam']),'');
assert.equal(validate(existing,slot('ot','2026-11-15','14:00'),['Adam']),'');
assert.equal(validate(existing,slot('ot','2026-12-12','14:00'),['Adam']),'');
assert.equal(validate(existing,speech,['Adam']),'');
assert.equal(validate([],slot('eip','2026-11-13','pagi'),['Adam','Sofia']),'');
assert.match(validate([],slot('eip','2026-11-14','pagi'),['Adam']),/tidak tersedia/);
assert.match(validate([],slot('speech','2026-11-13','09:00'),['Adam']),/tidak tersedia/);
assert.match(validate([],slot('ot','2026-11-14','15:15'),['Adam']),/tidak tersedia/);
assert.match(validate([],slot('eip','2026-02-30','pagi'),['Adam']),/tidak tersedia/);
assert.equal(context.shiftPlannerMonth('2026-01-31',1),'2026-02-28');
assert.equal(context.shiftPlannerMonth('2028-01-31',1),'2028-02-29');
assert.equal(context.shiftPlannerMonth('2026-12-15',1),'2027-01-15');
assert.equal(context.shiftPlannerDate('2026-12-31',1),'2027-01-01');
assert.equal(context.shiftPlannerDate('2026-03-01',-1),'2026-02-28');
assert.notEqual(context.slotKey('eip','2026-11-13','pagi'),context.slotKey('eip','2026-12-11','pagi'));
vm.runInContext(`if(therapySlots.length!==5||slotEnd(therapySlots.at(-1))!=='15:00')throw Error('Invalid last slot');for(let i=1;i<therapySlots.length;i++){const mins=t=>Number(t.slice(0,2))*60+Number(t.slice(3));if(mins(therapySlots[i])-mins(therapySlots[i-1])!==75)throw Error('Invalid interval');}`,context);
console.log('PASS: 5 therapy slots, date-scoped conflicts, weekday restrictions, month/year boundaries and leap years.');

const hana=slot('eip','2026-11-13','pagi','Cikgu Hana');
const mira=slot('eip','2026-11-13','pagi','Cikgu Mira');
const old=[{mode:'eip',date:'2026-11-13',time:'pagi',key:'eip-2026-11-13-pagi',staff:'Cikgu Hana',students:['Adam','Sofia']}];
const normalized=context.normalizePlannerBookings(old);
assert.equal(normalized[0].key,hana.key);
assert.equal(old[0].key,'eip-2026-11-13-pagi');
assert.equal(validate(old,mira,['Rayyan','Aisyah']),'');
assert.match(validate(old,mira,['Adam']),/kumpulan Cikgu Hana/);
assert.equal(validate(old,hana,['Adam','Sofia']),'');
assert.equal(validate(old,slot('eip','2026-11-13','petang','Cikgu Mira'),['Adam']),'');
assert.equal(validate(old,slot('eip','2026-11-16','pagi','Cikgu Mira'),['Adam']),'');
const both=[...normalized,{...mira,students:['Rayyan','Aisyah']}];
assert.equal(context.countOccupiedSlots(both),1);
assert.equal(both.filter(b=>b.key!==hana.key).length,1);
assert.equal(both.filter(b=>b.key!==hana.key)[0].staff,'Cikgu Mira');
console.log('PASS: separate teacher groups, legacy records, student conflicts and group-scoped removal.');
